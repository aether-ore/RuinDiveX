import { createHash } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

import {
  compileIndustrialV4AuthoredArtifact,
  stableIndustrialV4AuthoredArtifactText,
  verifyIndustrialV4AuthoredArtifact,
} from '../src/dungeon-augmentation/authored/AuthoredArtifactCompiler.js';
import {
  INDUSTRIAL_V4_AUTHORED_LEVEL_SOURCE,
} from '../src/dungeon-augmentation/authored/IndustrialV4AuthoredLevelSource.js';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputArgument = process.argv.find((argument) => argument.startsWith('--output='));
const outputPath = path.resolve(
  repositoryRoot,
  outputArgument?.slice('--output='.length)
    || 'artifacts/dungeon-augmentation-authored/industrial-v4-authored-r1.json',
);
const moduleOutputArgument = process.argv.find((argument) => (
  argument.startsWith('--module-output=')
));
const moduleOutputPath = path.resolve(
  repositoryRoot,
  moduleOutputArgument?.slice('--module-output='.length)
    || 'src/dungeon-augmentation/authored/IndustrialV4AuthoredArtifact.generated.js',
);
const checkOnly = process.argv.includes('--check');
const stdoutOnly = process.argv.includes('--stdout');

const first = compileIndustrialV4AuthoredArtifact(INDUSTRIAL_V4_AUTHORED_LEVEL_SOURCE);
const second = compileIndustrialV4AuthoredArtifact(INDUSTRIAL_V4_AUTHORED_LEVEL_SOURCE);
const firstText = stableIndustrialV4AuthoredArtifactText(first);
const secondText = stableIndustrialV4AuthoredArtifactText(second);
const firstPayload = gzipSync(Buffer.from(firstText, 'utf8'), { level: 9, mtime: 0 });
const secondPayload = gzipSync(Buffer.from(secondText, 'utf8'), { level: 9, mtime: 0 });
const buildReceipt = {
  schema: 'ruindivex-dungeon-augmentation-authored-build-receipt/v1',
  artifactId: first.artifactId,
  artifactRevision: first.artifactRevision,
  generationMode: first.generationMode,
  profileId: first.profileId,
  profileRevision: first.profileRevision,
  artifactHash: first.artifactHash,
  sourceContentHash: first.sourceContentHash,
  baseGeometryHash: first.baseGeometryHash,
  baseDraftDescriptorHash: first.baseDraftDescriptorHash,
  canonicalBaseRandomTapeHash: first.canonicalBaseRandomTapeHash,
  overlayPlanHash: first.overlayPlanHash,
  effectiveLayoutHash: first.effectiveLayoutHash,
  materializedLayoutHash: first.materializedLayoutHash,
  materializedLayoutDescriptorHash: first.materializedLayoutDescriptorHash,
  renderBatchManifestHash: first.renderBatchManifestHash,
  runtimeStateManifestHash: first.runtimeStateManifestHash,
  assetManifestHash: first.assetManifestHash,
  payloadCodecSchema: 'ruindivex-dungeon-augmentation-authored-payload-codec/v1',
  payloadEncoding: 'base64',
  payloadCompression: 'gzip',
  payloadCompressedByteLength: firstPayload.byteLength,
  payloadUncompressedByteLength: Buffer.byteLength(firstText, 'utf8'),
  payloadCompressedSha256: `sha256-${createHash('sha256')
    .update(firstPayload).digest('hex')}`,
};
const moduleText = '// Generated by scripts/compile-industrial-v4-authored-artifact.mjs.\n'
  + 'import { decodeIndustrialV4AuthoredArtifactPayload } from '
  + "'./AuthoredArtifactPayloadCodec.js';\n\n"
  + `const INDUSTRIAL_V4_AUTHORED_ARTIFACT_PAYLOAD = '${firstPayload.toString('base64')}';\n`
  + 'export const INDUSTRIAL_V4_AUTHORED_ARTIFACT_BUILD_RECEIPT = '
  + `Object.freeze(${JSON.stringify(buildReceipt)});\n`
  + 'export function loadIndustrialV4AuthoredArtifactPayload({ signal = null } = {}) {\n'
  + '  return decodeIndustrialV4AuthoredArtifactPayload({\n'
  + '    base64: INDUSTRIAL_V4_AUTHORED_ARTIFACT_PAYLOAD,\n'
  + '    receipt: INDUSTRIAL_V4_AUTHORED_ARTIFACT_BUILD_RECEIPT,\n'
  + '    signal,\n'
  + '  });\n'
  + '}\n';
if (firstText !== secondText || !firstPayload.equals(secondPayload)) {
  throw new Error('Industrial V4 authored compilation is nondeterministic.');
}

const verification = verifyIndustrialV4AuthoredArtifact(first);
if (!verification.accepted) {
  throw new Error(`Industrial V4 artifact verification failed: ${JSON.stringify(
    verification.errors,
  )}`);
}

if (stdoutOnly) {
  process.stdout.write(firstText);
} else if (checkOnly) {
  let existing;
  try {
    existing = await readFile(outputPath, 'utf8');
  } catch (error) {
    if (error?.code === 'ENOENT') {
      throw new Error(`Compiled artifact is missing: ${outputPath}`);
    }
    throw error;
  }
  if (existing !== firstText) {
    throw new Error(`Compiled artifact is stale: ${outputPath}`);
  }
  let existingModule;
  try {
    existingModule = await readFile(moduleOutputPath, 'utf8');
  } catch (error) {
    if (error?.code === 'ENOENT') {
      throw new Error(`Compiled artifact module is missing: ${moduleOutputPath}`);
    }
    throw error;
  }
  if (existingModule !== moduleText) {
    throw new Error(`Compiled artifact module is stale: ${moduleOutputPath}`);
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  const temporaryPath = `${outputPath}.tmp-${process.pid}`;
  await writeFile(temporaryPath, firstText, 'utf8');
  await rename(temporaryPath, outputPath);
  await mkdir(path.dirname(moduleOutputPath), { recursive: true });
  const temporaryModulePath = `${moduleOutputPath}.tmp-${process.pid}`;
  await writeFile(temporaryModulePath, moduleText, 'utf8');
  await rename(temporaryModulePath, moduleOutputPath);
}

if (!stdoutOnly) {
  process.stdout.write(`${JSON.stringify({
    accepted: true,
    mode: checkOnly ? 'check' : 'write',
    outputPath,
    moduleOutputPath,
    artifactId: first.artifactId,
    artifactHash: first.artifactHash,
    sourceContentHash: first.sourceContentHash,
    baseGeometryHash: first.baseGeometryHash,
    overlayPlanHash: first.overlayPlanHash,
    effectiveLayoutHash: first.effectiveLayoutHash,
    materializedLayoutHash: first.materializedLayoutHash,
    assetManifestHash: first.assetManifestHash,
    payloadCompressedByteLength: firstPayload.byteLength,
    payloadUncompressedByteLength: Buffer.byteLength(firstText, 'utf8'),
    composition: first.validationReceipt.composition,
  })}\n`);
}
